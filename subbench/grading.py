"""Offline batch grader using swebench harness."""

from __future__ import annotations

import json
import logging
import sqlite3
import time
from collections.abc import Callable, Sequence
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

from subbench.tasks.validate import find_report, run_harness

logger = logging.getLogger(__name__)
DEFAULT_DATASET_JSONL = Path("data/validation/dataset.jsonl")


def partition_into_unique_instance_batches(
    attempts: Sequence[dict[str, Any]],
) -> list[list[dict[str, Any]]]:
    """Partition attempts into batches where each batch contains strictly unique instance_ids.

    Satisfies SWE-bench requirement that predictions.jsonl cannot have duplicate instance_ids.
    """
    batches: list[list[dict[str, Any]]] = []
    for att in attempts:
        placed = False
        for b in batches:
            if not any(x["instance_id"] == att["instance_id"] for x in b):
                b.append(att)
                placed = True
                break
        if not placed:
            batches.append([att])
    return batches


def grade_attempt_empty(
    conn: sqlite3.Connection,
    attempt_id: int,
    swebench_version: str = "4.1.0",
) -> None:
    """Record a non-edit/empty-patch attempt as unresolved directly without Docker."""
    now_iso = datetime.now(UTC).isoformat()
    # Check if a grade already exists
    cur = conn.execute("SELECT id FROM grades WHERE attempt_id = ?", (attempt_id,))
    if cur.fetchone():
        conn.execute("DELETE FROM grades WHERE attempt_id = ?", (attempt_id,))

    conn.execute(
        """
        INSERT INTO grades (
            attempt_id, graded_at, swebench_version, resolved, patch_applied,
            fail_to_pass_json, pass_to_pass_json, report_path, log_path, error_text
        ) VALUES (?, ?, ?, 0, 0, '[]', '[]', NULL, NULL, 'empty_patch')
        """,
        (attempt_id, now_iso, swebench_version),
    )
    conn.execute("UPDATE attempts SET state = 'GRADED' WHERE id = ?", (attempt_id,))
    conn.commit()


def parse_instance_report(
    report_file: Path,
    instance_id: str,
) -> tuple[bool, bool, str, str]:
    """Parse a per-instance report.json generated by swebench."""
    try:
        data = json.loads(report_file.read_text(encoding="utf-8"))
        inst_data = data.get(instance_id, {})
        resolved = bool(inst_data.get("resolved", False))
        applied = bool(inst_data.get("patch_successfully_applied", False))
        tests = inst_data.get("tests_status", {})
        f2p = json.dumps(tests.get("FAIL_TO_PASS", {}))
        p2p = json.dumps(tests.get("PASS_TO_PASS", {}))
        return resolved, applied, f2p, p2p
    except Exception as e:
        logger.warning("Failed to parse instance report %s: %s", report_file, e)
        return False, False, "[]", "[]"


def grade_batch(
    conn: sqlite3.Connection,
    batch: list[dict[str, Any]],
    cycle_id: int,
    batch_idx: int,
    workdir: Path,
    dataset_jsonl: Path,
    harness_fn: Callable[..., Any] = run_harness,
    max_workers: int = 2,
    swebench_version: str = "4.1.0",
) -> None:
    """Grade a batch of attempts with unique instance_ids via the SWE-bench harness."""
    batch_dir = workdir / f"batch_{batch_idx}"
    batch_dir.mkdir(parents=True, exist_ok=True)

    model_name = f"subbench-c{cycle_id}-b{batch_idx}"
    preds_file = batch_dir / "predictions.jsonl"

    ids: list[str] = []
    with open(preds_file, "w", encoding="utf-8") as f:
        for att in batch:
            inst_id = att["instance_id"]
            patch_content = att["patch_content"]
            ids.append(inst_id)
            f.write(
                json.dumps(
                    {
                        "instance_id": inst_id,
                        "model_name_or_path": model_name,
                        "model_patch": patch_content,
                    }
                )
                + "\n"
            )

    run_id = f"eval-{int(time.time())}-{batch_idx}"
    logger.info("Running grading harness for batch %d (%d instances)...", batch_idx, len(ids))
    proc = harness_fn(
        dataset_jsonl=dataset_jsonl,
        predictions=preds_file,
        ids=ids,
        run_id=run_id,
        workdir=batch_dir,
        max_workers=max_workers,
    )

    summary_report = find_report(batch_dir, model_name, run_id)
    now_iso = datetime.now(UTC).isoformat()

    for att in batch:
        att_id = att["id"]
        inst_id = att["instance_id"]

        # Check for per-instance report.json
        eval_logs = batch_dir / "logs" / "run_evaluation" / run_id / model_name / inst_id
        inst_report_path = eval_logs / "report.json"
        inst_log_path = eval_logs / "run_instance.log"

        resolved = False
        applied = False
        f2p_json = "[]"
        p2p_json = "[]"
        rep_path_str: str | None = None
        log_path_str: str | None = None
        err_text: str | None = None

        if inst_report_path.exists():
            resolved, applied, f2p_json, p2p_json = parse_instance_report(inst_report_path, inst_id)
            rep_path_str = str(inst_report_path)
            if inst_log_path.exists():
                log_path_str = str(inst_log_path)
        elif summary_report:
            resolved = inst_id in summary_report.get("resolved_ids", [])
            applied = resolved or (inst_id not in summary_report.get("empty_patch_ids", []))
            rep_path_str = str(batch_dir / f"{model_name}.{run_id}.json")
            if not resolved and inst_id in summary_report.get("error_ids", []):
                err_text = "harness_evaluation_error"
        else:
            err_text = f"No grading report generated (rc={getattr(proc, 'returncode', -1)})"

        # Delete existing grade if present (for regrade)
        conn.execute("DELETE FROM grades WHERE attempt_id = ?", (att_id,))
        conn.execute(
            """
            INSERT INTO grades (
                attempt_id, graded_at, swebench_version, resolved, patch_applied,
                fail_to_pass_json, pass_to_pass_json, report_path, log_path, error_text
            ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
            """,
            (
                att_id,
                now_iso,
                swebench_version,
                1 if resolved else 0,
                1 if applied else 0,
                f2p_json,
                p2p_json,
                rep_path_str,
                log_path_str,
                err_text,
            ),
        )
        conn.execute("UPDATE attempts SET state = 'GRADED' WHERE id = ?", (att_id,))
    conn.commit()


def grade_cycle(
    conn: sqlite3.Connection,
    cycle_id: int,
    regrade: bool = False,
    max_workers: int = 2,
    harness_fn: Callable[..., Any] = run_harness,
    dataset_jsonl: Path = DEFAULT_DATASET_JSONL,
    workdir: Path | None = None,
) -> dict[str, Any]:
    """Grade all ungraded (or all if regrade=True) attempts for a cycle."""
    state_cond = "state IN ('QUOTA_POST', 'GRADED')" if regrade else "state = 'QUOTA_POST'"
    query = f"""
        SELECT id, config_id, instance_id, pass_index, seq, patch_path, patch_bytes
        FROM attempts
        WHERE cycle_id = ? AND {state_cond}
        ORDER BY id
    """
    rows = conn.execute(query, (cycle_id,)).fetchall()
    if not rows:
        logger.info("No attempts to grade for cycle %d", cycle_id)
        return {"graded": 0, "resolved": 0}

    grading_dir = workdir or (Path("artifacts") / "cycles" / f"cycle-{cycle_id}" / "grading")
    grading_dir.mkdir(parents=True, exist_ok=True)

    empty_attempts: list[dict[str, Any]] = []
    non_empty_attempts: list[dict[str, Any]] = []

    for r in rows:
        att_id = r[0]
        cfg_id = r[1]
        inst_id = r[2]
        pass_idx = r[3]
        seq = r[4]
        patch_path = r[5]
        patch_bytes = r[6]

        patch_content = ""
        if patch_path and Path(patch_path).exists():
            patch_content = Path(patch_path).read_text(encoding="utf-8", errors="replace").strip()

        att_dict = {
            "id": att_id,
            "config_id": cfg_id,
            "instance_id": inst_id,
            "pass_index": pass_idx,
            "seq": seq,
            "patch_path": patch_path,
            "patch_bytes": patch_bytes,
            "patch_content": patch_content,
        }

        if not patch_content or patch_bytes == 0:
            empty_attempts.append(att_dict)
        else:
            non_empty_attempts.append(att_dict)

    # 1. Short-circuit empty patch attempts
    for emp in empty_attempts:
        grade_attempt_empty(conn, emp["id"])

    # 2. Batch non-empty attempts with unique instance_ids
    batches = partition_into_unique_instance_batches(non_empty_attempts)
    for b_idx, batch in enumerate(batches):
        grade_batch(
            conn,
            batch=batch,
            cycle_id=cycle_id,
            batch_idx=b_idx,
            workdir=grading_dir,
            dataset_jsonl=dataset_jsonl,
            harness_fn=harness_fn,
            max_workers=max_workers,
        )

    # Summary
    cur = conn.execute(
        """
        SELECT count(*), coalesce(sum(resolved), 0)
        FROM grades g
        JOIN attempts a ON g.attempt_id = a.id
        WHERE a.cycle_id = ?
        """,
        (cycle_id,),
    )
    total_graded, total_resolved = cur.fetchone()
    logger.info("Cycle %d grading complete: %d/%d resolved", cycle_id, total_resolved, total_graded)
    return {"graded": total_graded, "resolved": total_resolved}
